export function computeAABB(points) {
    if (!points || points.length === 0) return [0, 0, 0, 0];
    let minX = points[0][0], maxX = points[0][0];
    let minY = points[0][1], maxY = points[0][1];
    for (let i = 1; i < points.length; i++) {
        const x = points[i][0], y = points[i][1];
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
    }
    return [minX, minY, maxX, maxY];
}

export function checkAABBOverlap(boxA, boxB, pad = 0.00002) {
    return !(
        boxA[2] + pad < boxB[0] ||
        boxA[0] - pad > boxB[2] ||
        boxA[3] + pad < boxB[1] ||
        boxA[1] - pad > boxB[3]
    );
}

export function isPointInPolygon(point, polygon) {
    if (!point || !polygon || polygon.length < 3) return false;
    const [px, py] = point;
    let inside = false;
    for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
        const xi = polygon[i][0], yi = polygon[i][1];
        const xj = polygon[j][0], yj = polygon[j][1];
        const intersect = ((yi > py) !== (yj > py)) &&
            (px < (xj - xi) * (py - yi) / (yj - yi) + xi);
        if (intersect) inside = !inside;
    }
    return inside;
}

export function segmentIntersectsSegment(a, b, c, d) {
    const denom = (b[0] - a[0]) * (d[1] - c[1]) - (b[1] - a[1]) * (d[0] - c[0]);
    if (Math.abs(denom) < 1e-12) return false;
    const t = ((c[0] - a[0]) * (d[1] - c[1]) - (c[1] - a[1]) * (d[0] - c[0])) / denom;
    const s = ((c[0] - a[0]) * (b[1] - a[1]) - (c[1] - a[1]) * (b[0] - a[0])) / denom;
    return t > 0 && t < 1 && s > 0 && s < 1;
}

export function segmentIntersectsPolygon(p1, p2, polygon) {
    if (!polygon || polygon.length < 2) return false;
    for (let i = 0; i < polygon.length - 1; i++) {
        if (segmentIntersectsSegment(p1, p2, polygon[i], polygon[i + 1])) {
            return true;
        }
    }
    return false;
}

export function distancePointToSegment(p, a, b) {
    const latM = 111320;
    const lngM = 55727;
    const px = p[0] * lngM, py = p[1] * latM;
    const ax = a[0] * lngM, ay = a[1] * latM;
    const bx = b[0] * lngM, by = b[1] * latM;
    const dx = bx - ax, dy = by - ay;
    const lenSq = dx * dx + dy * dy;
    if (lenSq === 0) return Math.hypot(px - ax, py - ay);
    let t = ((px - ax) * dx + (py - ay) * dy) / lenSq;
    t = Math.max(0, Math.min(1, t));
    return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
}

export function distancePointToPolygon(p, polygon) {
    if (!polygon || polygon.length < 2) return Infinity;
    if (isPointInPolygon(p, polygon)) return 0;
    let minDist = Infinity;
    for (let i = 0; i < polygon.length - 1; i++) {
        const d = distancePointToSegment(p, polygon[i], polygon[i + 1]);
        if (d < minDist) minDist = d;
    }
    return minDist;
}

export function distanceSegmentToPolygon(p1, p2, polygon, samples = 10) {
    if (segmentIntersectsPolygon(p1, p2, polygon)) return 0;
    let minDist = Math.min(distancePointToPolygon(p1, polygon), distancePointToPolygon(p2, polygon));
    for (let i = 1; i < samples; i++) {
        const t = i / samples;
        const mid = [p1[0] + (p2[0] - p1[0]) * t, p1[1] + (p2[1] - p1[1]) * t];
        const d = distancePointToPolygon(mid, polygon);
        if (d < minDist) minDist = d;
    }
    return minDist;
}

export function verifyCollisionTier1(segAABB, polyAABB) {
    return checkAABBOverlap(segAABB, polyAABB);
}

export function verifyCollisionTier2(points, polygon) {
    for (const pt of points) {
        if (isPointInPolygon(pt, polygon)) return false; // Collision detected
    }
    return true; // Free
}

export function verifyCollisionTier3(p1, p2, polygon) {
    return !segmentIntersectsPolygon(p1, p2, polygon);
}

export function verifyCollisionTier4(p1, p2, polygon, clearanceMeters = 0.8) {
    return distanceSegmentToPolygon(p1, p2, polygon) >= clearanceMeters;
}

export function verifySegmentCollision(p1, p2, polygon, options = {}) {
    const clearance = options.clearanceMeters !== undefined ? options.clearanceMeters : 0.8;
    const segAABB = computeAABB([p1, p2]);
    const polyAABB = computeAABB(polygon);

    // Tier 1: AABB Pre-filter
    if (!verifyCollisionTier1(segAABB, polyAABB)) {
        return { ok: true, tier: 1 };
    }

    // Tier 2: Point in Polygon
    if (!verifyCollisionTier2([p1, p2], polygon)) {
        return { ok: false, tier: 2, reason: 'point_inside_polygon' };
    }

    // Tier 3: Segment-Polygon Intersection
    if (!verifyCollisionTier3(p1, p2, polygon)) {
        return { ok: false, tier: 3, reason: 'segment_pierces_polygon' };
    }

    // Tier 4: Clearance Buffer
    if (clearance > 0 && !verifyCollisionTier4(p1, p2, polygon, clearance)) {
        return { ok: false, tier: 4, reason: 'clearance_buffer_breach' };
    }

    return { ok: true, tier: 4 };
}

export function verifyRouteAgainstBuildings(waypoints, buildings = PETROGRADKA_BUILDING_POLYGONS, options = {}) {
    if (!waypoints || waypoints.length < 2) return { ok: true, collisions: 0 };
    let collisions = 0;
    const details = [];

    for (let i = 0; i < waypoints.length - 1; i++) {
        const p1 = waypoints[i];
        const p2 = waypoints[i + 1];

        for (const bld of buildings) {
            const poly = bld.poly || bld;
            const res = verifySegmentCollision(p1, p2, poly, options);
            if (!res.ok) {
                collisions++;
                details.push({
                    segmentIndex: i,
                    from: p1,
                    to: p2,
                    buildingId: bld.id || 'unknown',
                    buildingName: bld.name || bld.street || 'building',
                    tier: res.tier,
                    reason: res.reason
                });
            }
        }
    }

    return {
        ok: collisions === 0,
        collisions,
        details
    };
}

export function auditNavMeshCollisions(graph = SIDEWALK_NAVMESH_GRAPH, buildings = PETROGRADKA_BUILDING_POLYGONS, options = {}) {
    let edgeCollisions = 0;
    let nodeCollisions = 0;

    for (const [nodeId, node] of Object.entries(graph.nodes)) {
        for (const bld of buildings) {
            const poly = bld.poly || bld;
            if (isPointInPolygon(node.coords, poly)) {
                nodeCollisions++;
            }
        }
    }

    for (const edge of graph.edges) {
        const p1 = graph.nodes[edge.from]?.coords;
        const p2 = graph.nodes[edge.to]?.coords;
        if (!p1 || !p2) continue;

        for (const bld of buildings) {
            const poly = bld.poly || bld;
            if (segmentIntersectsPolygon(p1, p2, poly)) {
                edgeCollisions++;
            }
        }
    }

    return {
        ok: nodeCollisions === 0 && edgeCollisions === 0,
        nodeCollisions,
        edgeCollisions
    };
}

