export function getPedestrianSegments(pedestrian) {
    if (!pedestrian || !pedestrian.waypoints || pedestrian.waypoints.length < 2) {
        return [];
    }

    if (pedestrian._cachedSegments) {
        return pedestrian._cachedSegments;
    }

    const wps = pedestrian.waypoints;
    const isLoop = Boolean(pedestrian.isLoop);

    let routePoints = [];
    if (isLoop) {
        routePoints = [...wps];
        const first = wps[0];
        const last = wps[wps.length - 1];
        if (first[0] !== last[0] || first[1] !== last[1]) {
            routePoints.push(first);
        }
    } else {
        routePoints = [...wps];
        for (let i = wps.length - 2; i >= 1; i--) {
            routePoints.push(wps[i]);
        }
    }

    const segments = [];
    let cumulativeDist = 0;

    for (let i = 0; i < routePoints.length - 1; i++) {
        const from = routePoints[i];
        const to = routePoints[i + 1];
        const dist = calculateDistanceMeters(from, to);
        const bearing = calculateBearing(from, to);

        segments.push({
            index: i,
            from,
            to,
            distance: dist,
            bearing,
            startDist: cumulativeDist,
            endDist: cumulativeDist + dist
        });

        cumulativeDist += dist;
    }

    pedestrian._cachedSegments = segments;
    pedestrian._totalDistance = cumulativeDist;

    return segments;
}

export function interpolatePedestrianPosition(pedestrian, timeElapsedMs = 0, options = {}) {
    if (!pedestrian || !pedestrian.waypoints || pedestrian.waypoints.length === 0) {
        return {
            id: pedestrian?.id || 'unknown',
            name: pedestrian?.name || '',
            state: AGENT_STATE.WALKING,
            lng: 30.3080,
            lat: 59.9590,
            coords: [30.3080, 59.9590],
            bearing: 0,
            speed: 0,
            gaitPhase: 0,
            thought: '✨',
            currentThought: '✨',
            dialogue: null,
            progress: 0,
            segmentIndex: 0
        };
    }

    const waypoints = pedestrian.waypoints;
    const effectiveTime = (Number(timeElapsedMs) || 0) + (pedestrian.timeOffsetMs || 0);

    // Diurnal routine evaluation
    const currentHour = options.simHour !== undefined ? options.simHour : (new Date().getHours() + new Date().getMinutes() / 60);
    const diurnalPeriod = getDiurnalPeriod(currentHour);
    const routine = pedestrian.diurnalRoutines?.[diurnalPeriod] || { speedMult: 1.0, thoughts: pedestrian.thoughts, action: '' };

    const thoughts = routine.thoughts && routine.thoughts.length > 0 ? routine.thoughts : (pedestrian.thoughts || ['✨']);
    const thoughtInterval = pedestrian.thoughtIntervalMs || 4000;
    const thoughtIndex = Math.floor((effectiveTime / thoughtInterval) % thoughts.length);
    const currentThought = thoughts[(thoughtIndex + thoughts.length) % thoughts.length];

    if (waypoints.length === 1) {
        const p = waypoints[0];
        return {
            id: pedestrian.id,
            name: pedestrian.name,
            state: AGENT_STATE.WALKING,
            lng: p[0],
            lat: p[1],
            coords: [p[0], p[1]],
            bearing: 0,
            speed: 0,
            gaitPhase: 0,
            thought: currentThought,
            currentThought,
            dialogue: null,
            progress: 0,
            segmentIndex: 0,
            diurnalPeriod,
            action: routine.action
        };
    }

    const segments = getPedestrianSegments(pedestrian);
    const totalDistance = pedestrian._totalDistance || segments.reduce((sum, s) => sum + s.distance, 0);

    if (totalDistance <= 0 || segments.length === 0) {
        const p = waypoints[0];
        return {
            id: pedestrian.id,
            name: pedestrian.name,
            state: AGENT_STATE.WALKING,
            lng: p[0],
            lat: p[1],
            coords: [p[0], p[1]],
            bearing: 0,
            speed: 0,
            gaitPhase: 0,
            thought: currentThought,
            currentThought,
            dialogue: null,
            progress: 0,
            segmentIndex: 0,
            diurnalPeriod,
            action: routine.action
        };
    }

    // Nominal walking speed modulated by diurnal schedule
    const baseSpeed = Number(pedestrian.speed) || 1.3;
    const effectiveSpeed = baseSpeed * (routine.speedMult || 1.0);

    // Periodic Idle Stop (pause at storefronts / benches)
    const cycleDurationMs = 45000;
    const pauseDurationMs = 7000;
    const cycleTime = effectiveTime % cycleDurationMs;
    const isPausedAtPOI = cycleTime > (cycleDurationMs - pauseDurationMs);

    let state = isPausedAtPOI ? AGENT_STATE.IDLE_STOP : AGENT_STATE.WALKING;
    let walkTimeMs = isPausedAtPOI ? effectiveTime - (cycleTime - (cycleDurationMs - pauseDurationMs)) : effectiveTime;

    let dialogue = options.activeDialogue || null;
    let targetHeading = null;
    if (options.isGreeting) {
        state = AGENT_STATE.GREETING;
        if (options.greetBearing !== undefined) {
            targetHeading = options.greetBearing;
        }
    }

    const totalWalkedMeters = (walkTimeMs / 1000) * effectiveSpeed;
    const progressMeters = ((totalWalkedMeters % totalDistance) + totalDistance) % totalDistance;

    let activeSegment = segments[0];
    for (let i = 0; i < segments.length; i++) {
        const seg = segments[i];
        if (progressMeters >= seg.startDist && progressMeters <= seg.endDist) {
            activeSegment = seg;
            break;
        }
    }

    const segDist = activeSegment.distance;
    const segT = segDist > 0 ? (progressMeters - activeSegment.startDist) / segDist : 0;
    const t = Math.max(0, Math.min(1, segT));

    const lng = activeSegment.from[0] + (activeSegment.to[0] - activeSegment.from[0]) * t;
    const lat = activeSegment.from[1] + (activeSegment.to[1] - activeSegment.from[1]) * t;
    const bearing = targetHeading !== null ? targetHeading : activeSegment.bearing;

    const stepLength = 0.65;
    const gaitPhase = state === AGENT_STATE.IDLE_STOP ? 0 : (progressMeters / stepLength) * Math.PI;

    return {
        id: pedestrian.id,
        name: pedestrian.name,
        state,
        lng: Number(lng.toFixed(6)),
        lat: Number(lat.toFixed(6)),
        coords: [Number(lng.toFixed(6)), Number(lat.toFixed(6))],
        bearing,
        speed: state === AGENT_STATE.WALKING ? effectiveSpeed : (state === AGENT_STATE.GREETING ? 0.1 : 0),
        gaitPhase,
        thought: currentThought,
        currentThought,
        dialogue,
        progress: Number((progressMeters / totalDistance).toFixed(4)),
        segmentIndex: activeSegment.index,
        diurnalPeriod,
        action: routine.action
    };
}

export function checkSocialProximity(pedestrianStates, leraState, cooldowns, nowMs = Date.now()) {
    const greetings = [];
    if (!pedestrianStates || pedestrianStates.length === 0) return greetings;

    const allEntities = [...pedestrianStates];
    if (leraState && leraState.coords) {
        allEntities.push({
            id: 'lera',
            name: 'Лера',
            coords: leraState.coords,
            lng: leraState.coords[0],
            lat: leraState.coords[1]
        });
    }

    const n = allEntities.length;
    for (let i = 0; i < n; i++) {
        for (let j = i + 1; j < n; j++) {
            const entA = allEntities[i];
            const entB = allEntities[j];

            const dist = calculateDistanceMeters(entA.coords, entB.coords);
            if (dist <= PROXIMITY_THRESHOLD_METERS) {
                const pairKey = [entA.id, entB.id].sort().join(':');
                const hasGreeted = cooldowns.has(pairKey);
                const lastGreetTime = cooldowns.get(pairKey) || 0;

                if (!hasGreeted || (nowMs - lastGreetTime >= GREETING_COOLDOWN_MS)) {
                    const dInfo = getDialogueKey(entA.id, entB.id);
                    if (dInfo) {
                        const dialogue = SOCIAL_DIALOGUES[dInfo.key];
                        const textA = dInfo.isReversed ? dialogue.b : dialogue.a;
                        const textB = dInfo.isReversed ? dialogue.a : dialogue.b;

                        cooldowns.set(pairKey, nowMs);

                        const bearingAtoB = calculateBearing(entA.coords, entB.coords);
                        const bearingBtoA = (bearingAtoB + 180) % 360;

                        greetings.push({
                            idA: entA.id,
                            idB: entB.id,
                            dialogueA: textA,
                            dialogueB: textB,
                            bearingA: bearingAtoB,
                            bearingB: bearingBtoA,
                            distanceMeters: Number(dist.toFixed(1)),
                            expiresAt: nowMs + GREETING_DURATION_MS
                        });
                    }
                }
            }
        }
    }

    return greetings;
}

