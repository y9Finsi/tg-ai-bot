/**
 * Calculates geodesic distance in meters between two [lng, lat] coordinates (Haversine formula).
 * @param {[number, number]} coord1 - [lng, lat]
 * @param {[number, number]} coord2 - [lng, lat]
 * @returns {number} distance in meters
 */
export function calculateDistanceMeters(coord1, coord2) {
    if (!coord1 || !coord2) return 0;
    const [lng1, lat1] = coord1;
    const [lng2, lat2] = coord2;

    const dLat = (lat2 - lat1) * Math.PI / 180;
    const dLng = (lng2 - lng1) * Math.PI / 180;
    const radLat1 = lat1 * Math.PI / 180;
    const radLat2 = lat2 * Math.PI / 180;

    const a =
        Math.sin(dLat / 2) * Math.sin(dLat / 2) +
        Math.cos(radLat1) * Math.cos(radLat2) *
        Math.sin(dLng / 2) * Math.sin(dLng / 2);

    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    return 6371000 * c; // Earth radius in meters
}

/**
 * Calculates compass bearing from coord1 to coord2 in degrees [0, 360).
 * 0 = North, 90 = East, 180 = South, 270 = West.
 * @param {[number, number]} coord1 - [lng, lat]
 * @param {[number, number]} coord2 - [lng, lat]
 * @returns {number} bearing in degrees (0..359.9)
 */
export function calculateBearing(coord1, coord2) {
    if (!coord1 || !coord2) return 0;
    const [lng1, lat1] = coord1;
    const [lng2, lat2] = coord2;

    const radLat1 = lat1 * Math.PI / 180;
    const radLat2 = lat2 * Math.PI / 180;
    const dLng = (lng2 - lng1) * Math.PI / 180;

    const y = Math.sin(dLng) * Math.cos(radLat2);
    const x =
        Math.cos(radLat1) * Math.sin(radLat2) -
        Math.sin(radLat1) * Math.cos(radLat2) * Math.cos(dLng);

    const brng = (Math.atan2(y, x) * 180 / Math.PI + 360) % 360;
    return Number(brng.toFixed(1));
}

