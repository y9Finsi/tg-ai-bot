/**
 * Finds shortest zero-collision sidewalk path between startCoords and targetCoords
 * using Dijkstra / A* over SIDEWALK_NAVMESH_GRAPH.
 * @param {[number, number]} startCoords - [lng, lat]
 * @param {[number, number]} targetCoords - [lng, lat]
 * @param {object} graph - NavMesh graph
 * @returns {Array<[number, number]>} smoothed array of [lng, lat] waypoints
 */
export function findNavMeshPath(startCoords, targetCoords, graph = SIDEWALK_NAVMESH_GRAPH) {
    if (!startCoords || !targetCoords) return [];
    if (calculateDistanceMeters(startCoords, targetCoords) < 1.0) {
        return [startCoords, targetCoords];
    }

    const nodes = graph.nodes || {};
    const edges = graph.edges || [];
    const nodeKeys = Object.keys(nodes);
    if (nodeKeys.length === 0) {
        return [startCoords, targetCoords];
    }

    // 1. Find nearest graph nodes to start and target
    let startNodeId = nodeKeys[0];
    let minStartDist = Infinity;
    let targetNodeId = nodeKeys[0];
    let minTargetDist = Infinity;

    for (const id of nodeKeys) {
        const nCoords = nodes[id].coords;
        const dStart = calculateDistanceMeters(startCoords, nCoords);
        if (dStart < minStartDist) {
            minStartDist = dStart;
            startNodeId = id;
        }
        const dTarget = calculateDistanceMeters(targetCoords, nCoords);
        if (dTarget < minTargetDist) {
            minTargetDist = dTarget;
            targetNodeId = id;
        }
    }

    // 2. Build adjacency list with metric geodesic edge weights
    const adj = {};
    for (const id of nodeKeys) {
        adj[id] = [];
    }
    for (const e of edges) {
        if (nodes[e.from] && nodes[e.to]) {
            const d = calculateDistanceMeters(nodes[e.from].coords, nodes[e.to].coords);
            adj[e.from].push({ to: e.to, dist: d });
            adj[e.to].push({ to: e.from, dist: d });
        }
    }

    // 3. Dijkstra search
    const distances = {};
    const prev = {};
    const unvisited = new Set(nodeKeys);

    for (const id of nodeKeys) {
        distances[id] = Infinity;
    }
    distances[startNodeId] = 0;

    while (unvisited.size > 0) {
        let curr = null;
        let lowestDist = Infinity;
        for (const id of unvisited) {
            if (distances[id] < lowestDist) {
                lowestDist = distances[id];
                curr = id;
            }
        }

        if (!curr || lowestDist === Infinity || curr === targetNodeId) {
            break;
        }

        unvisited.delete(curr);

        for (const edge of adj[curr]) {
            if (unvisited.has(edge.to)) {
                const alt = distances[curr] + edge.dist;
                if (alt < distances[edge.to]) {
                    distances[edge.to] = alt;
                    prev[edge.to] = curr;
                }
            }
        }
    }

    // 4. Reconstruct path
    const pathNodeIds = [];
    let step = targetNodeId;
    if (prev[step] !== undefined || step === startNodeId) {
        while (step) {
            pathNodeIds.unshift(step);
            step = prev[step];
        }
    } else {
        pathNodeIds.push(startNodeId);
        if (targetNodeId !== startNodeId) pathNodeIds.push(targetNodeId);
    }

    // 5. Construct smoothed waypoint coordinates array
    const waypoints = [startCoords];
    for (const id of pathNodeIds) {
        const pt = nodes[id].coords;
        const lastPt = waypoints[waypoints.length - 1];
        if (calculateDistanceMeters(lastPt, pt) > 1.2) {
            waypoints.push(pt);
        }
    }
    const lastPt = waypoints[waypoints.length - 1];
    if (calculateDistanceMeters(lastPt, targetCoords) > 1.2) {
        waypoints.push(targetCoords);
    } else if (waypoints.length === 1) {
        waypoints.push(targetCoords);
    }

    return waypoints;
}

/**
 * Creates an active transit mission for Lera.
 * Supports location IDs ('petrogradka_home', 'cafe_sloy', etc.) or explicit [lng, lat] coordinates.
 */
export function createLeraTransit(fromLocOrCoords, toLocOrCoords, durationSec = 0, options = {}) {
    const resolveCoords = (val) => {
        if (!val) return [30.3049, 59.9589];
        if (Array.isArray(val) && val.length >= 2) return [Number(val[0]), Number(val[1])];
        if (typeof val === 'string') {
            const locKey = val.toLowerCase();
            if (locKey === 'petrogradka_home' || locKey === 'home') return [30.3049, 59.9589];
            if (locKey === 'cafe_sloy' || locKey === 'sloy') return [30.312186, 59.961159];
            if (locKey === 'vkusvill_lenina' || locKey === 'vkusvill') return [30.2986, 59.9563];
            if (locKey === 'spbgik' || locKey === 'university') return [30.3197, 59.9427];
            if (locKey === 'showroom_work' || locKey === 'showroom') return [30.2731, 59.9386];
            if (locKey === 'bar_rubinsteina' || locKey === 'bar') return [30.3437, 59.9294];
            const node = SIDEWALK_NAVMESH_GRAPH.nodes[locKey];
            if (node) return node.coords;
        }
        return [30.3049, 59.9589];
    };

    const fromCoords = resolveCoords(fromLocOrCoords);
    const toCoords = resolveCoords(toLocOrCoords);

    const waypoints = findNavMeshPath(fromCoords, toCoords);

    let cumulative = 0;
    const segments = [];
    for (let i = 0; i < waypoints.length - 1; i++) {
        const p1 = waypoints[i];
        const p2 = waypoints[i + 1];
        const dist = calculateDistanceMeters(p1, p2);
        const brng = calculateBearing(p1, p2);
        segments.push({
            index: i,
            from: p1,
            to: p2,
            distance: dist,
            startDist: cumulative,
            endDist: cumulative + dist,
            bearing: brng
        });
        cumulative += dist;
    }

    const totalDistance = cumulative;

    let finalDurationSec = Number(durationSec) || 0;
    if (finalDurationSec <= 0) {
        finalDurationSec = Math.max(12, Math.min(45, Math.round(totalDistance / 1.35)));
    }

    return {
        from: fromLocOrCoords,
        to: toLocOrCoords,
        fromCoords,
        targetPos: toCoords,
        targetName: options.targetName || (typeof toLocOrCoords === 'string' ? toLocOrCoords : 'Цель'),
        targetAction: options.targetAction || '',
        waypoints,
        segments,
        totalDistance: Number(totalDistance.toFixed(1)),
        durationSec: finalDurationSec,
        startTime: options.startTime || Date.now()
    };
}

/**
 * Interpolates Lera's kinematic position, speed, and heading along an active transit mission.
 */
export function interpolateTransitPosition(transit, nowMs = Date.now()) {
    if (!transit || !transit.targetPos) {
        return {
            coords: [30.3049, 59.9589],
            lng: 30.3049,
            lat: 59.9589,
            bearing: 0,
            speed: 0,
            progress: 1.0,
            gaitPhase: 0,
            isFinished: true
        };
    }

    if (!transit.segments || transit.segments.length === 0 || transit.totalDistance <= 0) {
        return {
            coords: transit.targetPos,
            lng: transit.targetPos[0],
            lat: transit.targetPos[1],
            bearing: 0,
            speed: 0,
            progress: 1.0,
            gaitPhase: 0,
            isFinished: true
        };
    }

    const elapsedSec = Math.max(0, (nowMs - transit.startTime) / 1000);
    const progress = Math.min(1.0, elapsedSec / transit.durationSec);
    const distanceCovered = progress * transit.totalDistance;

    if (progress >= 1.0) {
        const lastSeg = transit.segments[transit.segments.length - 1];
        return {
            coords: transit.targetPos,
            lng: transit.targetPos[0],
            lat: transit.targetPos[1],
            bearing: lastSeg ? lastSeg.bearing : 0,
            speed: 0,
            progress: 1.0,
            gaitPhase: 0,
            isFinished: true,
            distanceCovered: transit.totalDistance,
            totalDistance: transit.totalDistance
        };
    }

    let activeSeg = transit.segments[0];
    for (let i = 0; i < transit.segments.length; i++) {
        const seg = transit.segments[i];
        if (distanceCovered >= seg.startDist && distanceCovered <= seg.endDist) {
            activeSeg = seg;
            break;
        }
    }

    const segDist = activeSeg.distance;
    const segT = segDist > 0 ? (distanceCovered - activeSeg.startDist) / segDist : 0;
    const t = Math.max(0, Math.min(1, segT));

    const lng = activeSeg.from[0] + (activeSeg.to[0] - activeSeg.from[0]) * t;
    const lat = activeSeg.from[1] + (activeSeg.to[1] - activeSeg.from[1]) * t;

    const nominalSpeed = Math.min(1.8, Math.max(1.2, transit.totalDistance > 0 ? 1.4 : 0));
    const gaitPhase = (distanceCovered / 0.65) * Math.PI;

    return {
        coords: [Number(lng.toFixed(6)), Number(lat.toFixed(6))],
        lng: Number(lng.toFixed(6)),
        lat: Number(lat.toFixed(6)),
        bearing: activeSeg.bearing,
        speed: nominalSpeed,
        progress: Number(progress.toFixed(4)),
        gaitPhase,
        isFinished: false,
        distanceCovered: Number(distanceCovered.toFixed(1)),
        totalDistance: Number(transit.totalDistance.toFixed(1))
    };
}

