export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
    if (!lat1 || !lon1 || !lat2 || !lon2) return 0;
    const R = 6371;
    const dLat = (lat2 - lat1) * Math.PI / 180;
    const dLon = (lon2 - lon1) * Math.PI / 180;
    const a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
              Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
              Math.sin(dLon / 2) * Math.sin(dLon / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    return Number((R * c).toFixed(2));
}

export function calculateTransitOptions(fromCoords, toCoords) {
    const distKm = calculateDistanceKm(fromCoords[1], fromCoords[0], toCoords[1], toCoords[0]);
    
    // Пешком: ~4.8 км/ч -> ~12.5 мин на 1 км (минимум 3 мин)
    const walkMinutes = Math.max(3, Math.round(distKm * 12.5));
    
    // Такси: посадка 180 руб + 35 руб/км, скорость ~28 км/ч в городе (минимум 4 мин)
    const taxiPrice = Math.round(180 + distKm * 35);
    const taxiMinutes = Math.max(4, Math.round(distKm * 2.2 + 3));

    return {
        distKm,
        walk: {
            durationMinutes: walkMinutes,
            costRubles: 0,
            energyCost: Math.min(25, Math.max(3, Math.round(distKm * 4))),
            hungerCost: Math.min(20, Math.max(2, Math.round(distKm * 3)))
        },
        taxi: {
            durationMinutes: taxiMinutes,
            costRubles: taxiPrice,
            energyCost: 1,
            hungerCost: 1
        }
    };
}

